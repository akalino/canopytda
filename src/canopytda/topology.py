def _cell_sort_key(_cell_id):
    """Return the natural stratum and sheet order for one cell."""

    return int(_cell_id[0]), int(_cell_id[1])


def _stratum_records(_canopy):
    """Return base strata indexed by identifier."""

    return dict(
        (_stratum["id"], dict(_stratum))
        for _stratum in _canopy["base"]["strata"]
    )


def _constructible_cells(_canopy, _strata):
    """Build one symbolic total-space cell per stored sheet and stratum."""

    _cells = []
    for _fiber in _canopy["representative_fibers"]:
        _stratum = _strata[_fiber["stratum_id"]]
        for _point in _fiber["points"]:
            _cell = {}
            _cell["cell_id"] = _point["sheet_id"]
            _cell["sheet_id"] = _point["sheet_id"]
            _cell["stratum_id"] = _fiber["stratum_id"]
            _cell["pair_index"] = _point["pair_index"]
            _cell["pair"] = _point["pair"]
            _cell["homology_dimension"] = _point["homology_dimension"]
            _cell["kind"] = _stratum["kind"]
            _cell["start"] = float(_stratum["start"])
            _cell["end"] = float(_stratum["end"])
            _cell["left_closed"] = bool(_stratum["left_closed"])
            _cell["right_closed"] = bool(_stratum["right_closed"])
            _cell["representative_parameter"] = float(
                _fiber["representative_parameter"]
            )
            _cell["representative_eta"] = _point["eta"]
            _cells.append(_cell)
    return tuple(
        sorted(
            _cells,
            key=lambda _cell: _cell_sort_key(_cell["cell_id"])
        )
    )


def _relation_record(_kind, _source, _target, _stratum_ids, _continuation_id, _incidence_id=None):
    """Return one witnessed trajectory relation between constructible cells."""

    _record = {}
    _record["relation_id"] = None
    _record["kind"] = _kind
    _record["source_cell_id"] = _source
    _record["target_cell_id"] = _target
    _record["stratum_ids"] = tuple(_stratum_ids)
    _record["continuation_id"] = _continuation_id
    _record["incidence_id"] = _incidence_id
    return _record


def _trajectory_relations(_canopy):
    """Collect every self and incidence relation without selecting a branch."""

    _relations = []
    for _fiber in _canopy["representative_fibers"]:
        _stratum_id = _fiber["stratum_id"]
        for _continuation in _fiber["self_continuations"]:
            for _source, _target in _continuation["mapping"]:
                _relations.append(
                    _relation_record(
                        "self_continuation",
                        _source,
                        _target,
                        (_stratum_id,),
                        _continuation["id"]
                    )
                )

    for _incidence in _canopy["incidences"]:
        _stratum_ids = (
            _incidence["source_stratum_id"],
            _incidence["target_stratum_id"]
        )
        for _continuation in _incidence["continuations"]:
            for _source, _target in _continuation["mapping"]:
                _relations.append(
                    _relation_record(
                        "incidence_continuation",
                        _source,
                        _target,
                        _stratum_ids,
                        _continuation["id"],
                        _incidence["incidence_id"]
                    )
                )

    for _relation_id, _record in enumerate(_relations):
        _record["relation_id"] = _relation_id
    return tuple(_relations)


def _adjacency_from_relations(_cells, _relations):
    """Return symmetric trajectory adjacency on the symbolic cells."""

    _adjacency = dict(
        (_cell["cell_id"], {_cell["cell_id"]})
        for _cell in _cells
    )
    for _relation in _relations:
        _source = _relation["source_cell_id"]
        _target = _relation["target_cell_id"]
        _adjacency[_source].add(_target)
        _adjacency[_target].add(_source)
    return dict(
        (
            _cell_id,
            tuple(sorted(_neighbors, key=_cell_sort_key))
        )
        for _cell_id, _neighbors in _adjacency.items()
    )


def build_canopy_topology(_canopy):
    """Build the finite constructible topology of an A-canopy.

    The returned object stores symbolic cells and all witnessed trajectory
    relations.  Relations are treated symmetrically because every stored
    continuation is a bijection and hence can be traversed in reverse.  No
    structurality label is used during construction; comparison with the
    independently computed labels is available through
    :func:`topology_structurality_certificate`.

    :param _canopy: Complete one-parameter A-canopy presentation.
    :type _canopy: ACanopy or mapping
    :return: Finite symbolic topology record.
    :rtype: dict
    """

    validate_a_canopy(_canopy)
    _canopy = (_canopy.to_record() if isinstance(_canopy, ACanopy)
               else deepcopy(_canopy))
    if _canopy.get("representation") != "finite_constructible_one_parameter":
        raise ValueError("Topology construction requires a finite one-parameter canopy")
    if not _canopy.get("complete", False):
        raise ValueError("Topology construction requires complete continuations")

    _strata = _stratum_records(_canopy)
    _cells = _constructible_cells(_canopy, _strata)
    _relations = _trajectory_relations(_canopy)
    _adjacency = _adjacency_from_relations(_cells, _relations)

    _topology = {}
    _topology["output_record_version"] = OUTPUT_RECORD_VERSION
    _topology["mathematical_scope"] = MATHEMATICAL_SCOPE
    _topology["tie_break_rule"] = TIE_BREAK_RULE
    _topology["object_type"] = "finite A-canopy topology"
    _topology["paper_definition"] = "Theorem 3.8 trajectory basis"
    _topology["representation"] = "finite_constructible_one_parameter_topology"
    _topology["scope"] = "fixed_complex_stratified_interval"
    _topology["canopy"] = _canopy
    _topology["base"] = dict(_canopy["base"])
    _topology["cells"] = _cells
    _topology["relations"] = _relations
    _topology["adjacency"] = _adjacency
    _topology["cell_count"] = len(_cells)
    _topology["relation_count"] = len(_relations)
    _topology["complete"] = True
    _topology["topology_materialized"] = True
    _topology["continuum_enumerated"] = False
    _topology["basis_representation"] = "symbolic_constructible_cells"
    validate_canopy_topology(_topology)
    return _topology


def _topology_data(_topology):
    """Return validated core topology records."""

    if not hasattr(_topology, "__getitem__"):
        raise TypeError("Canopy topology must be a mapping")
    try:
        _object_type = _topology["object_type"]
        _canopy = _topology["canopy"]
        _cells = tuple(_topology["cells"])
        _relations = tuple(_topology["relations"])
        _adjacency = dict(_topology["adjacency"])
    except KeyError as _error:
        raise ValueError(
            "Canopy topology is missing {}".format(_error.args[0])
        ) from _error
    except TypeError as _error:
        raise ValueError("Canopy topology records must be iterable") from _error
    if _object_type != "finite A-canopy topology":
        raise ValueError("Object is not a finite A-canopy topology")
    validate_a_canopy(_canopy)
    return _canopy, _cells, _relations, _adjacency


def validate_canopy_topology(_topology):
    """Validate a finite constructible topology presentation.

    :param _topology: Candidate topology returned by
        :func:`build_canopy_topology`.
    :type _topology: mapping
    :return: The validated input mapping.
    :rtype: mapping
    :raises ValueError: If a cell or trajectory invariant fails.
    """

    _canopy, _cells, _relations, _adjacency = _topology_data(_topology)
    if _topology.get("representation") != "finite_constructible_one_parameter_topology":
        raise ValueError("Unsupported canopy topology representation")
    if not _topology.get("complete", False):
        raise ValueError("Canopy topology must certify complete relations")
    if _topology.get("base") != _canopy["base"]:
        raise ValueError("Topology base does not match its A-canopy")
    if _cells != _constructible_cells(_canopy, _stratum_records(_canopy)):
        raise ValueError("Topology cells do not match the A-canopy fibers")
    if _relations != _trajectory_relations(_canopy):
        raise ValueError("Topology relations do not match the A-canopy continuations")

    _cell_ids = tuple(_cell["cell_id"] for _cell in _cells)
    if len(set(_cell_ids)) != len(_cell_ids):
        raise ValueError("Topology repeats a constructible cell identifier")
    if set(_cell_ids) != set(_adjacency):
        raise ValueError("Topology adjacency does not cover every cell")
    if set(_cell_ids) != set(_sheet_id for _sheet_id, _stratum_id in _canopy["projection"]):
        raise ValueError("Topology cells do not agree with the canopy projection")

    _expected = dict((_cell_id, {_cell_id}) for _cell_id in _cell_ids)
    for _relation in _relations:
        try:
            _source = _relation["source_cell_id"]
            _target = _relation["target_cell_id"]
            _kind = _relation["kind"]
        except (KeyError, TypeError) as _error:
            raise ValueError("Topology relation is incomplete") from _error
        if _source not in _expected or _target not in _expected:
            raise ValueError("Topology relation refers to an unknown cell")
        if _kind not in {"self_continuation", "incidence_continuation"}:
            raise ValueError("Topology relation has an unknown kind")
        _expected[_source].add(_target)
        _expected[_target].add(_source)

    for _cell_id, _neighbors in _adjacency.items():
        if tuple(sorted(_neighbors, key=_cell_sort_key)) != tuple(
            sorted(_expected[_cell_id], key=_cell_sort_key)
        ):
            raise ValueError("Topology adjacency does not match its relations")
    if _topology.get("cell_count") != len(_cells):
        raise ValueError("Stored topology cell count is incorrect")
    if _topology.get("relation_count") != len(_relations):
        raise ValueError("Stored topology relation count is incorrect")
    return _topology


def _parameter_tolerance(_topology):
    """Return a scale-aware parameter tolerance."""

    _start, _end = tuple(float(_value) for _value in _topology["base"]["domain"])
    _scale = max(1.0, abs(_start), abs(_end), abs(_end - _start))
    return 1e-12 * _scale


def _window_contains(_parameter, _left, _right, _domain, _tolerance):
    """Return whether a relative-open base window contains a parameter."""

    _domain_start, _domain_end = _domain
    _left_ok = _parameter > _left + _tolerance
    _right_ok = _parameter < _right - _tolerance
    if abs(_parameter - _domain_start) <= _tolerance:
        _left_ok = _left <= _domain_start + _tolerance
    if abs(_parameter - _domain_end) <= _tolerance:
        _right_ok = _right >= _domain_end - _tolerance
    return _left_ok and _right_ok


def _stratum_at_parameter(_topology, _parameter):
    """Return the unique base stratum containing a parameter."""

    _parameter = _finite_float(_parameter, "Base parameter")

    _tolerance = _parameter_tolerance(_topology)
    _candidates = []
    for _stratum in _topology["base"]["strata"]:
        _start = float(_stratum["start"])
        _end = float(_stratum["end"])
        if _parameter < _start - _tolerance or _parameter > _end + _tolerance:
            continue
        if abs(_parameter - _start) <= _tolerance and not _stratum["left_closed"]:
            continue
        if abs(_parameter - _end) <= _tolerance and not _stratum["right_closed"]:
            continue
        _candidates.append(_stratum)
    if len(_candidates) != 1:
        raise ValueError("Parameter does not lie in exactly one topology stratum")
    return _parameter, _candidates[0]


def _resolve_point(_topology, _parameter, _pair):
    """Resolve a parameter and chosen pair to one symbolic canopy point."""

    _parameter, _stratum = _stratum_at_parameter(_topology, _parameter)
    _matches = []
    for _cell in _topology["cells"]:
        if _cell["stratum_id"] != _stratum["id"]:
            continue
        if _cell["pair"] == _pair:
            _matches.append(_cell)
    if len(_matches) != 1:
        raise ValueError("Chosen pair does not identify one point in the fiber")

    _point = {}
    _point["parameter"] = _parameter
    _point["stratum_id"] = _stratum["id"]
    _point["cell_id"] = _matches[0]["cell_id"]
    _point["pair"] = _matches[0]["pair"]
    _point["kind"] = _stratum["kind"]
    return _point


def _local_window(_topology, _parameter, _stratum):
    """Return a canonical window containing no unrelated event stratum."""

    _domain_start, _domain_end = tuple(
        float(_value)
        for _value in _topology["base"]["domain"]
    )
    _span = max(_domain_end - _domain_start, 1.0)
    if _domain_start == _domain_end:
        return _domain_start - 0.25 * _span, _domain_end + 0.25 * _span

    if _stratum["kind"] == "interval":
        _start = float(_stratum["start"])
        _end = float(_stratum["end"])
        _left = 0.5 * (_start + _parameter)
        _right = 0.5 * (_parameter + _end)
        if abs(_parameter - _start) <= _parameter_tolerance(_topology):
            _left = _domain_start
        if abs(_parameter - _end) <= _parameter_tolerance(_topology):
            _right = _domain_end
        return _left, _right

    _critical = sorted(
        {
            _domain_start,
            _domain_end,
            *(
                float(_item["start"])
                for _item in _topology["base"]["strata"]
                if _item["kind"] == "point"
            )
        }
    )
    _previous = tuple(_value for _value in _critical if _value < _parameter)
    _following = tuple(_value for _value in _critical if _value > _parameter)
    _left = _domain_start
    _right = _domain_end
    if _previous:
        _left = 0.5 * (_previous[-1] + _parameter)
    if _following:
        _right = 0.5 * (_parameter + _following[0])
    return _left, _right


def _normalize_window(_topology, _parameter, _stratum, _base_window):
    """Validate or construct a relative-open base window."""

    if _base_window is None:
        _left, _right = _local_window(
            _topology,
            _parameter,
            _stratum
        )
    else:
        try:
            _left, _right = tuple(
                _finite_float(_value, "Base window endpoint")
                for _value in _base_window)
        except (TypeError, ValueError) as _error:
            raise ValueError("Base window must contain two finite endpoints") from _error
    if _left >= _right:
        raise ValueError("Base window endpoints must be strictly increasing")

    _domain = tuple(float(_value) for _value in _topology["base"]["domain"])
    _tolerance = _parameter_tolerance(_topology)
    if not _window_contains(
        _parameter,
        _left,
        _right,
        _domain,
        _tolerance
    ):
        raise ValueError("Base window must contain the seed parameter")
    return _left, _right


def _stratum_piece(_topology, _stratum, _window):
    """Return the nonempty intersection of a stratum and a base window."""

    _left, _right = _window
    _domain = tuple(float(_value) for _value in _topology["base"]["domain"])
    _tolerance = _parameter_tolerance(_topology)
    _start = float(_stratum["start"])
    _end = float(_stratum["end"])

    if _stratum["kind"] == "point":
        if not _window_contains(
            _start,
            _left,
            _right,
            _domain,
            _tolerance
        ):
            return None
        _piece = {}
        _piece["kind"] = "point"
        _piece["start"] = _start
        _piece["end"] = _end
        _piece["left_closed"] = True
        _piece["right_closed"] = True
        return _piece

    _piece_start = max(_start, _left)
    _piece_end = min(_end, _right)
    if _piece_start >= _piece_end - _tolerance:
        return None
    _left_closed = False
    _right_closed = False
    if abs(_piece_start - _start) <= _tolerance:
        _left_closed = bool(_stratum["left_closed"])
    if abs(_piece_end - _end) <= _tolerance:
        _right_closed = bool(_stratum["right_closed"])
    if abs(_piece_start - _domain[0]) <= _tolerance and _left <= _domain[0] + _tolerance:
        _left_closed = bool(_stratum["left_closed"])
    if abs(_piece_end - _domain[1]) <= _tolerance and _right >= _domain[1] - _tolerance:
        _right_closed = bool(_stratum["right_closed"])

    _piece = {}
    _piece["kind"] = "interval"
    _piece["start"] = _piece_start
    _piece["end"] = _piece_end
    _piece["left_closed"] = _left_closed
    _piece["right_closed"] = _right_closed
    return _piece


def _active_cells(_topology, _window):
    """Return cells whose base strata meet a window and their base pieces."""

    _strata = dict(
        (_stratum["id"], _stratum)
        for _stratum in _topology["base"]["strata"]
    )
    _active = {}
    for _cell in _topology["cells"]:
        _piece = _stratum_piece(
            _topology,
            _strata[_cell["stratum_id"]],
            _window
        )
        if _piece is not None:
            _active[_cell["cell_id"]] = _piece
    return _active


def _reachable_cells(_topology, _seed_cell_id, _active):
    """Return the trajectory component of a seed in an induced cell graph."""

    if _seed_cell_id not in _active:
        raise ValueError("Seed cell does not meet the requested base window")
    _visited = set()
    _stack = [_seed_cell_id]
    while _stack:
        _current = _stack.pop()
        if _current in _visited:
            continue
        _visited.add(_current)
        for _neighbor in _topology["adjacency"][_current]:
            if _neighbor in _active and _neighbor not in _visited:
                _stack.append(_neighbor)
    return tuple(sorted(_visited, key=_cell_sort_key))


def _basis_neighborhood(_topology, _parameter, _pair, _base_window):
    """Build one basis neighborhood after topology validation."""

    _point = _resolve_point(_topology, _parameter, _pair)
    _stratum = next(
        _item
        for _item in _topology["base"]["strata"]
        if _item["id"] == _point["stratum_id"]
    )
    _window = _normalize_window(
        _topology,
        _point["parameter"],
        _stratum,
        _base_window
    )
    _active = _active_cells(_topology, _window)
    _cell_ids = _reachable_cells(
        _topology,
        _point["cell_id"],
        _active
    )
    _cell_by_id = dict(
        (_cell["cell_id"], _cell)
        for _cell in _topology["cells"]
    )
    _members = []
    for _cell_id in _cell_ids:
        _member = dict(_cell_by_id[_cell_id])
        _member["base_piece"] = dict(_active[_cell_id])
        _members.append(_member)

    _result = {}
    _result["object_type"] = "A-canopy basis neighborhood"
    _result["seed"] = _point
    _result["base_window"] = _window
    _result["cell_ids"] = _cell_ids
    _result["members"] = tuple(_members)
    _result["stratum_ids"] = tuple(
        sorted({_member["stratum_id"] for _member in _members})
    )
    _result["complete"] = True
    return _result


def canopy_basis_neighborhood(_topology, _parameter, _pair, _base_window=None):
    """Return a finite symbolic trajectory-basis neighborhood.

    The base window is interpreted as an open interval relative to the canopy
    base.  At a domain endpoint, supplying that endpoint as a window endpoint
    therefore still represents a relative-open one-sided neighborhood.

    :param _topology: Finite topology from :func:`build_canopy_topology`.
    :type _topology: mapping
    :param _parameter: Base parameter of the seed point.
    :type _parameter: real
    :param _pair: Chosen simplex pair identifying the seed fiber point.
    :type _pair: tuple
    :param _base_window: Optional two-endpoint relative-open base window.
    :type _base_window: tuple or None
    :return: Symbolic basis-neighborhood record.
    :rtype: dict
    """

    validate_canopy_topology(_topology)
    return _basis_neighborhood(
        _topology,
        _parameter,
        _pair,
        _base_window
    )


def canopy_separation_certificate(_topology, _left_parameter, _left_pair, _right_parameter, _right_pair):
    """Certify whether two finite-presentation canopy points are separable.

    Points over distinct base parameters are separated by disjoint base
    neighborhoods.  Points in one fiber are tested using canonical local
    trajectory neighborhoods containing no unrelated event.

    :param _topology: Finite A-canopy topology.
    :type _topology: mapping
    :param _left_parameter: Base parameter of the first point.
    :type _left_parameter: real
    :param _left_pair: Chosen pair of the first point.
    :type _left_pair: tuple
    :param _right_parameter: Base parameter of the second point.
    :type _right_parameter: real
    :param _right_pair: Chosen pair of the second point.
    :type _right_pair: tuple
    :return: Separation result with finite witnesses.
    :rtype: dict
    """

    validate_canopy_topology(_topology)
    _left = _resolve_point(_topology, _left_parameter, _left_pair)
    _right = _resolve_point(_topology, _right_parameter, _right_pair)
    _tolerance = _parameter_tolerance(_topology)
    _result = {}
    _result["left_point"] = _left
    _result["right_point"] = _right
    _result["complete"] = True

    if _left["cell_id"] == _right["cell_id"] and abs(
        _left["parameter"] - _right["parameter"]
    ) <= _tolerance:
        _result["distinct"] = False
        _result["separable"] = False
        _result["reason"] = "same_point"
        _result["intersection_cell_ids"] = (_left["cell_id"],)
        return _result

    _result["distinct"] = True
    if abs(_left["parameter"] - _right["parameter"]) > _tolerance:
        _midpoint = 0.5 * (_left["parameter"] + _right["parameter"])
        if _left["parameter"] < _right["parameter"]:
            _windows = (
                (_topology["base"]["domain"][0], _midpoint),
                (_midpoint, _topology["base"]["domain"][1])
            )
        else:
            _windows = (
                (_midpoint, _topology["base"]["domain"][1]),
                (_topology["base"]["domain"][0], _midpoint)
            )
        _result["separable"] = True
        _result["reason"] = "distinct_base_parameters"
        _result["witness_base_windows"] = _windows
        _result["intersection_cell_ids"] = ()
        return _result

    _stratum = next(
        _item
        for _item in _topology["base"]["strata"]
        if _item["id"] == _left["stratum_id"]
    )
    _window = _local_window(
        _topology,
        _left["parameter"],
        _stratum
    )
    _left_neighborhood = _basis_neighborhood(
        _topology,
        _left["parameter"],
        _left["pair"],
        _base_window=_window
    )
    _right_neighborhood = _basis_neighborhood(
        _topology,
        _right["parameter"],
        _right["pair"],
        _base_window=_window
    )
    _intersection = set(_left_neighborhood["cell_ids"]).intersection(
        _right_neighborhood["cell_ids"]
    )
    _result["separable"] = not bool(_intersection)
    _result["reason"] = (
        "disjoint_local_trajectory_neighborhoods"
        if not _intersection
        else "intersecting_local_trajectory_neighborhoods"
    )
    _result["base_window"] = _window
    _result["left_neighborhood"] = _left_neighborhood
    _result["right_neighborhood"] = _right_neighborhood
    _result["intersection_cell_ids"] = tuple(
        sorted(_intersection, key=_cell_sort_key)
    )
    return _result


def canopy_points_separable(_topology, _left_parameter, _left_pair, _right_parameter, _right_pair):
    """Return whether two distinct canopy points admit disjoint neighborhoods.

    :param _topology: Finite A-canopy topology.
    :type _topology: mapping
    :param _left_parameter: Base parameter of the first point.
    :type _left_parameter: real
    :param _left_pair: Chosen pair of the first point.
    :type _left_pair: tuple
    :param _right_parameter: Base parameter of the second point.
    :type _right_parameter: real
    :param _right_pair: Chosen pair of the second point.
    :type _right_pair: tuple
    :return: ``True`` exactly when the two points are distinct and separable.
    :rtype: bool
    """

    return canopy_separation_certificate(
        _topology,
        _left_parameter,
        _left_pair,
        _right_parameter,
        _right_pair
    )["separable"]


def local_topology_components(_topology, _parameter):
    """Return local trajectory components meeting one canopy fiber.

    Each component contains the symbolic cells present in the canonical local
    basis neighborhood of its fiber points.  More than one fiber point in one
    component is the finite certificate that those points are nonseparable.

    :param _topology: Finite A-canopy topology.
    :type _topology: mapping
    :param _parameter: Base parameter to inspect.
    :type _parameter: real
    :return: Local components and the common base window.
    :rtype: dict
    """

    validate_canopy_topology(_topology)
    _parameter, _stratum = _stratum_at_parameter(_topology, _parameter)
    _fiber_cells = tuple(
        _cell
        for _cell in _topology["cells"]
        if _cell["stratum_id"] == _stratum["id"]
    )
    _window = _local_window(_topology, _parameter, _stratum)
    _component_sets = []
    for _cell in _fiber_cells:
        _neighborhood = _basis_neighborhood(
            _topology,
            _parameter,
            _cell["pair"],
            _base_window=_window
        )
        _component = frozenset(_neighborhood["cell_ids"])
        if _component not in _component_sets:
            _component_sets.append(_component)

    _components = []
    _fiber_ids = {_cell["cell_id"] for _cell in _fiber_cells}
    _cell_by_id = dict(
        (_cell["cell_id"], _cell)
        for _cell in _topology["cells"]
    )
    for _component_id, _component_set in enumerate(_component_sets):
        _cell_ids = tuple(sorted(_component_set, key=_cell_sort_key))
        _component_fiber_ids = tuple(
            _cell_id
            for _cell_id in _cell_ids
            if _cell_id in _fiber_ids
        )
        _record = {}
        _record["component_id"] = _component_id
        _record["cell_ids"] = _cell_ids
        _record["fiber_cell_ids"] = _component_fiber_ids
        _record["fiber_pairs"] = tuple(
            _cell_by_id[_cell_id]["pair"]
            for _cell_id in _component_fiber_ids
        )
        _record["non_hausdorff"] = len(_component_fiber_ids) > 1
        _components.append(_record)

    _result = {}
    _result["parameter"] = _parameter
    _result["stratum_id"] = _stratum["id"]
    _result["kind"] = _stratum["kind"]
    _result["base_window"] = _window
    _result["components"] = tuple(_components)
    _result["component_count"] = len(_components)
    _result["fiber_cardinality"] = len(_fiber_cells)
    _result["complete"] = True
    return _result


def canopy_hausdorff_classes(_topology):
    """Return every local class containing nonseparable fiber points.

    :param _topology: Finite A-canopy topology.
    :type _topology: mapping
    :return: Complete local Hausdorff certificate.
    :rtype: dict
    """

    validate_canopy_topology(_topology)
    _classes = []
    for _stratum in _topology["base"]["strata"]:
        _parameter = float(_stratum["representative_parameter"])
        _local = local_topology_components(_topology, _parameter)
        for _component in _local["components"]:
            if not _component["non_hausdorff"]:
                continue
            _record = dict(_component)
            _record["stratum_id"] = _stratum["id"]
            _record["kind"] = _stratum["kind"]
            _record["parameter"] = _parameter
            _record["base_domain"] = (
                float(_stratum["start"]),
                float(_stratum["end"])
            )
            _classes.append(_record)

    _result = {}
    _result["classes"] = tuple(_classes)
    _result["class_count"] = len(_classes)
    _result["hausdorff"] = not bool(_classes)
    _result["complete"] = True
    _result["scope"] = _topology["scope"]
    return _result


def constructible_closure(_topology, _cell_ids):
    """Compute the closure of a union of whole constructible cells.

    A target cell is included exactly when each sufficiently small canonical
    trajectory neighborhood meets the selected cell union.  Because the
    subset and topology are constructible over a finite one-dimensional
    stratification, the local trajectory component is constant on every base
    stratum and provides a complete finite test.

    :param _topology: Finite A-canopy topology.
    :type _topology: mapping
    :param _cell_ids: Constructible cells whose union is to be closed.
    :type _cell_ids: iterable
    :return: Input, closure and added-boundary cell identifiers.
    :rtype: dict
    """

    validate_canopy_topology(_topology)
    try:
        _selected = set(_cell_ids)
    except TypeError as _error:
        raise TypeError("Constructible cell identifiers must be iterable") from _error
    _known = {_cell["cell_id"] for _cell in _topology["cells"]}
    if not _selected.issubset(_known):
        raise ValueError("Constructible subset contains an unknown cell")

    _local_neighborhoods = {}
    for _cell in _topology["cells"]:
        _neighborhood = _basis_neighborhood(
            _topology,
            _cell["representative_parameter"],
            _cell["pair"],
            None
        )
        _local_neighborhoods[_cell["cell_id"]] = set(
            _neighborhood["cell_ids"]
        )

    _closure = set(_selected)
    _changed = True
    while _changed:
        _changed = False
        for _cell in _topology["cells"]:
            _cell_id = _cell["cell_id"]
            if _cell_id in _closure:
                continue
            if _closure.intersection(_local_neighborhoods[_cell_id]):
                _closure.add(_cell_id)
                _changed = True

    _input_ids = tuple(sorted(_selected, key=_cell_sort_key))
    _closure_ids = tuple(sorted(_closure, key=_cell_sort_key))
    _boundary_ids = tuple(
        sorted(_closure.difference(_selected), key=_cell_sort_key)
    )
    _result = {}
    _result["input_cell_ids"] = _input_ids
    _result["closure_cell_ids"] = _closure_ids
    _result["boundary_cell_ids"] = _boundary_ids
    _result["input_cell_count"] = len(_input_ids)
    _result["closure_cell_count"] = len(_closure_ids)
    _result["boundary_cell_count"] = len(_boundary_ids)
    _result["complete"] = True
    _result["scope"] = "unions_of_whole_constructible_cells"
    return _result


def topology_structurality_certificate(_topology):
    """Compare topology-derived nonseparability with structurality labels.

    This is a cross-check rather than part of topology construction.  The
    topology is built only from continuations; the expected pairs are read
    afterward from the independent structurality certificate stored by the
    A-canopy.

    :param _topology: Finite A-canopy topology.
    :type _topology: mapping
    :return: Event-by-event agreement certificate.
    :rtype: dict
    """

    validate_canopy_topology(_topology)
    _canopy = _topology["canopy"]
    _events = []
    for _event in _canopy["structurality"]["events"]:
        _local = local_topology_components(
            _topology,
            _event["parameter"]
        )
        _actual = set()
        for _component in _local["components"]:
            if _component["non_hausdorff"]:
                _actual.update(_component["fiber_pairs"])

        _expected = set()
        for _group in _event["structural_points"]:
            _expected.update(_group["non_hausdorff_pairs"])
        _record = {}
        _record["parameter"] = float(_event["parameter"])
        _record["event_stratum_id"] = _event["event_stratum_id"]
        _record["topology_non_hausdorff_pairs"] = tuple(
            sorted(_actual, key=repr)
        )
        _record["structurality_non_hausdorff_pairs"] = tuple(
            sorted(_expected, key=repr)
        )
        _record["agrees"] = _actual == _expected
        _events.append(_record)

    _result = {}
    _result["events"] = tuple(_events)
    _result["all_events_agree"] = all(
        _event["agrees"]
        for _event in _events
    )
    _result["complete"] = True
    _result["independent_construction"] = True
    return _result


class CanopyTopology(Mapping):
    """Finite symbolic topology induced by an A-canopy's continuations.

    The class represents basis neighborhoods by cells over one-dimensional
    base strata. It keeps every certified continuation and retains the source
    A-canopy record for downstream D-canopy construction. Its closure query
    applies to unions of *whole* constructible cells; a subset that enters or
    exits a cell at an interior parameter must first refine that cell.

    :param _canopy: Complete A-canopy object or output record.
    :type _canopy: ACanopy or mapping
    """

    __slots__ = ("_record",)

    def __init__(self, _canopy):
        if hasattr(self, "_record"):
            raise AttributeError("CanopyTopology is immutable")
        object.__setattr__(self, "_record", build_canopy_topology(_canopy))

    def __setattr__(self, _name, _value):
        raise AttributeError("CanopyTopology is immutable")

    def __delattr__(self, _name):
        raise AttributeError("CanopyTopology is immutable")

    def __getitem__(self, _key):
        """Return one detached topology record value."""
        return deepcopy(self._record[_key])

    def __iter__(self):
        """Iterate through the finite record's field names."""
        return iter(self._record)

    def __len__(self):
        """Return the number of finite record fields."""
        return len(self._record)

    @property
    def cells(self):
        """Return one symbolic cell per stratum sheet."""
        return deepcopy(self._record["cells"])

    @property
    def relations(self):
        """Return all self and adjacent continuation witnesses."""
        return deepcopy(self._record["relations"])

    @property
    def canopy(self):
        """Return a detached record of the source A-canopy."""
        return deepcopy(self._record["canopy"])

    def to_record(self):
        """Return an independent copy of the symbolic topology."""
        return deepcopy(self._record)

    def basis_neighborhood(self, _parameter, _pair, _base_window=None):
        """Return a symbolic trajectory neighborhood of one canopy point."""
        return canopy_basis_neighborhood(
            self, _parameter, _pair, _base_window)

    def separation_certificate(self, _left_parameter, _left_pair,
                               _right_parameter, _right_pair):
        """Explain whether two canopy points have disjoint neighborhoods."""
        return canopy_separation_certificate(
            self, _left_parameter, _left_pair,
            _right_parameter, _right_pair)

    def points_separable(self, _left_parameter, _left_pair,
                         _right_parameter, _right_pair):
        """Test whether two distinct canopy points can be separated."""
        return canopy_points_separable(
            self, _left_parameter, _left_pair,
            _right_parameter, _right_pair)

    def local_components(self, _parameter):
        """Return local trajectory components meeting one fiber."""
        return local_topology_components(self, _parameter)

    def hausdorff_classes(self):
        """Return nonseparable point classes for all base strata."""
        return canopy_hausdorff_classes(self)

    def closure(self, _cell_ids):
        """Close a union of whole constructible cells."""
        return constructible_closure(self, _cell_ids)

    def structurality_certificate(self):
        """Cross-check topology against the independent event labels."""
        return topology_structurality_certificate(self)
