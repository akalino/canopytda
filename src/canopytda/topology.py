r"""Finite symbolic topology for constructible one-parameter A-canopies.

The A-canopy topology in Theorem 3.8 is generated by trajectory
neighborhoods.  The total space contains continuously many points even when
the base is an interval, so this module does not enumerate it.  Instead, it
uses the interval and event strata already stored by :mod:`a_canopy` and
represents each sheet over a stratum as one constructible cell.

Continuation maps generate relations between these cells.  Restricting the
relations to an open base window gives a finite representation of a basis
neighborhood.  This is enough to certify local separation, recover the
non-Hausdorff fibers in Example 3.12 and compute closures of unions of whole
constructible cells.  The latter operation is the prerequisite for the
D-canopy construction in Definition 4.1 and Theorem 4.4.

The implementation is deliberately limited to the complete, fixed-complex,
one-dimensional finite presentations returned by
:func:`canopytda.a_canopy.build_a_canopy`.  It makes no claim to materialize
the topology for an arbitrary parameter space.
"""

from collections.abc import Mapping
from copy import deepcopy

from .a_canopy import ACanopy
from .a_canopy import validate_a_canopy
from .contract import MATHEMATICAL_SCOPE
from .contract import OUTPUT_RECORD_VERSION
from .contract import TIE_BREAK_RULE
from .utils import _finite_float


__all__ = ["CanopyTopology", "build_canopy_topology", "canopy_basis_neighborhood"]
__all__ += ["canopy_hausdorff_classes", "canopy_points_separable"]
